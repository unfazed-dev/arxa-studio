check('rows: honest content search (empty fetch)', client.includes('searchSessions: async () => ({ items: [], hasMore: false })'))
check('rows: trash surface wired (Q6)', client.includes('function TrashSection(') && client.includes('trash: () => orgStore.toggleTrash()'))
check('rows: locale relabels aboard', client.includes('"section.workspaces": "Organisations"'))
check('rows: stock Workspaces label superseded in overrides only', !client.includes('"section.workspaces": "Workspaces",\n\t\t\t\t"section.sessions"'))
check('rows: add flow opens the create-organisation modal (Q3, webview-safe)',
  client.includes('new Event("arxa-create-org")') && client.includes('function OrgCreateModal(') && client.includes('window.addEventListener("arxa-create-org", open)'))
check('rows: window.prompt is gone (Tauri WKWebView never implements it)', !client.includes('window.prompt('))
check('rows: location field opens the OS folder locator (Tauri dialog when injected, host osascript locator otherwise)',
  client.includes('window.__TAURI__.dialog') && client.includes('directory: true') && client.includes('pick-folder'))
check('host: macOS folder locator route exists', hostSrc().includes('choose folder') && hostSrc().includes('pick-folder'))
check('rows: first-run root action wired both sides (D36)',
  client.includes('"workspace.root"') && (() => {
    const hostSrc = readFileSync(join(here, 'lib', 'index.js'), 'utf8')
    return hostSrc.includes("action === 'workspace.root'") && hostSrc.includes('saveWorkspaceRoot(expanded)')
  })())
check('rows: shell New-session is org-aware (Q5)', client.includes('org.new-session') && client.includes('Open an organisation first'))
check('rows: OrgSection block deleted', !client.includes('OrgSection'))

// ---- 3b. workspace rows (org-model-v2 Phase C: D70/D71) ------------------------
check('rows-c: WorkspaceRowsSection aboard (the rows ARE the tree)', client.includes('function WorkspaceRowsSection('))
check('rows-c: OrgTreeSection dissolved', !client.includes('OrgTreeSection') && !client.includes('treeRows'))
check('rows-c: selection face + gated startSession splice', client.includes('selectRow(rowId)') && client.includes('workspace.new-session') && client.includes('const sel = orgStore.get().selectedRowId;'))
check('rows-c: selection hint + section label in both locales', client.includes('"rows.section": "Workspaces"') && client.includes('"newSession.selectFirst": "Select a workspace to start a session"') && client.includes('"rows.section": "工作区"'))
check('rows-c: server snapshot serves rows (category + project rowIds)', hostSrc().includes("rowId: 'category:'") && hostSrc().includes("rowId: 'project:'"))
check('rows-c: server act maps rowId → scoped session', hostSrc().includes("'workspace.new-session'") && hostSrc().includes('cur.newSession(undefined, proj)'))

// ---- 4. drift gate ------------------------------------------------------------
// The committed client.js must equal shell+workspace regenerated, byte for
// byte. A hand-edit to client.js (or a stale snippet) goes RED here — fix the
// source (script/snippets), never the generated file. rc-bump policy lives in
// scripts/gen-workspace.mjs.
{
  const rootDir = join(here, '..', '..')
  const r = spawnSync(process.execPath, [join(rootDir, 'scripts', 'gen-workspace.mjs')], {
    cwd: rootDir, encoding: 'utf8', timeout: 60_000,
  })
  const regen = r.stdout ?? ''
  check('drift gate: client.js equals both transforms regenerated',
    r.status === 0 && regen === client,
    r.status === 0 ? 'byte drift — regenerate, or fix scripts/gen-*.mjs / snippets' : String(r.stderr).slice(0, 200))
}

// ---- 5. original dsh packages byte-identical ----------------------------------
// Parent-walk resolution: works from the main checkout AND from a git
// worktree nested under it (no node_modules of its own).
const hashPkg = (specifier, expected) => {
  const pkgDir = dirname(createRequire(import.meta.url).resolve(specifier + '/package.json'))
  const files = []
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const f = join(d, e.name)
      e.isDirectory() ? walk(f) : files.push(f)
    }
  }
  walk(pkgDir)
  const hash = createHash('sha256')
  for (const f of files) {
    hash.update(relative(pkgDir, f))
    hash.update('\0')
    hash.update(readFileSync(f))
    hash.update('\0')
  }
  const got = hash.digest('hex')
  return { got, ok: got === expected }
}
{
  const s = hashPkg('@deepseek-ai/dsh-client-ui-sidebar',
    '04d3a1afb6793bd9de0a26eb82b1266ecdf78da03899c5c32ac4258bf242c4e7')
  check('reference: dsh sidebar package byte-identical', s.ok, 'expected 04d3a1af…')
  const w = hashPkg('@deepseek-ai/dsh-client-ui-workspace',
    'db871ccc02577da5a5fe31420456b78ca390d40d2cc0a75322a120d218e810e3')
  check('reference: dsh workspace package byte-identical', w.ok, 'expected db871ccc…')
}

// ---- 6. registration wired ---------------------------------------------------
const bin = readFileSync(join(repo, 'bin', 'arxa-studio.mjs'), 'utf8')
check('registration: profile dependency', bin.includes("'arxa-sidebar': `file:${sidebarDir}`"))
check('registration: BY_NAME_PLUGINS', /BY_NAME_PLUGINS = \[[^\]]*'arxa-sidebar'/.test(bin))
check('registration: packed-mode copy list', bin.includes("['arxa-sidebar', sidebarDir]"))
const patch = readFileSync(join(repo, 'profile', 'cordis.patch.yml'), 'utf8')
check('registration: arxa-sidebar inserted', /id: arxa-sidebar\s*\n\s*name: arxa-sidebar/.test(patch))
check('registration: stock ui-sidebar disabled', /- id: ui-sidebar\s*\n\s*disabled: true/.test(patch))
check('registration: stock ui-workspace disabled (rows world owns the section)',
  /- id: ui-workspace\s*\n\s*disabled: true/.test(patch))

// ---- 7. host half + lifecycle rows faces --------------------------------------
const host = await import('./lib/index.js')
check('host: SEAM_LIFECYCLE_STUBBED declared', typeof host.SEAM_LIFECYCLE_STUBBED === 'boolean')
check('host: cta-state module gone', !readFileSync(join(here, 'lib', 'index.js'), 'utf8').includes('cta-state'))
let mod = null
try { mod = await import('arxa-file-org-shell') } catch {}
if (!mod) {
  try { mod = await import(new URL('../file-org-shell/lib/index.js', import.meta.url).href) } catch {}
}
check('seam: arxa-file-org-shell resolves with createOrgLifecycle', typeof mod?.createOrgLifecycle === 'function')
{
  // renameOrg is a verb ON an instance — build one against a throwaway root.
  const { mkdtempSync } = await import('node:fs')
  const os = await import('node:os')
  const svc = mod.createOrgLifecycle({ workspaceRoot: mkdtempSync(join(os.tmpdir(), 'arxa-rows-')) })
  check('rows face: lifecycle exposes renameOrg (D41 manifest-only)', typeof svc.renameOrg === 'function')
}
check('rows face: host-served read-only exports (listSessions/listTrash)', typeof mod?.listSessions === 'function' && typeof mod?.listTrash === 'function')
check('rows face: workspace-root discovery exported', typeof mod?.loadWorkspaceRoot === 'function')

// ---- 8. pendingInteraction producer-consumer wiring (D63) ----------------------
// The producer is dsh itself: client-runtime SessionManager classifies
// question/requested mux frames into SessionSummary.pendingInteraction
// (approval | plan-review | question — 0.1.1-rc.2). The sidebar consumes it
// in three places; regeneration dropping any one silently strands the union
// (rows would never show the waiting pills), so pin all three.
check('wiring: session rows spread pendingInteraction',
  client.includes('...s.pendingInteraction === void 0 ? {} : { pendingInteraction: s.pendingInteraction }'))
check('wiring: search rows spread pendingInteraction',
  client.includes('...summary.pendingInteraction === void 0 ? {} : { pendingInteraction: summary.pendingInteraction }'))
check('wiring: status switch covers the closed union',
  client.includes('case "approval":') && client.includes('case "plan-review":')
  && client.includes('case "question":') && client.includes('assertNever(node.pendingInteraction)'))
check('wiring: runtime producer present (SessionManager pendingInteractions)',
  (() => {
    try {
      const rt = readFileSync(join(repo, 'node_modules', '@deepseek-ai', 'dsh-client-runtime', 'lib', 'client.js'), 'utf8')
      return rt.includes('pendingInteractions') && rt.includes('questionInteractionStatus')
    } catch { return false }
  })())

console.log(failures === 0 ? '\narxa-sidebar selftest: ALL GREEN' : `\narxa-sidebar selftest: ${failures} FAILURE(S)`)
process.exit(failures === 0 ? 0 : 1)
