#!/usr/bin/env node
// arxa-sidebar selftest — rows-world gate (docs/plans/sidebar-org-rethink.md):
//   1. manifest shape (repo plugin convention: dsh.client.inject + lib/client.js
//      UI half, lib/index.js server half, zero runtime dependencies)
//   2. composed client headers (gen-workspace + gen-sidebar, dsh 0.1.1-rc.2)
//   3. rows-world content: org store, OrgBrowser slot, locale relabels,
//      trash surface, shell New-session org-awareness; OrgSection GONE
//   4. drift gate: regenerate (shell + workspace transform) and byte-compare
//   5. both stock dsh packages byte-identical (content hashes)
//   6. registration wired (bin/arxa-studio.mjs + profile/cordis.patch.yml:
//      stock ui-sidebar AND ui-workspace disabled — one sidebar world active)
//   7. host half: rows state/action surface + lifecycle rows faces present
