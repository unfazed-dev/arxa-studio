#!/usr/bin/env node
// gen-insight-css.mjs — the Insight panel's styling is a verbatim copy of the
// stock tool grammar (docs/plans/git-card-stock-dock-rebuild.md §4). This
// script lifts `ToolRow.module.css` + `ToolDetails.module.css` (CSS literal
// and class map) out of the installed @deepseek-ai/dsh-client-ui-tool bundle,
// rewrites both hashed prefixes to `aXa_ins_` so the copy never collides with
// the stock tag, and splices the result into plugins/artifact-viewer/lib/client.js
// between the `>>> insight-css` / `<<< insight-css` markers.
//
//   node scripts/gen-insight-css.mjs --write   # rewrite the region in client.js
//   node scripts/gen-insight-css.mjs --check   # exit 1 when the region drifts
//
// The artifact-viewer selftest runs `--check`, so a dsh upgrade that moves the
// stock CSS fails the gate instead of silently leaving the panel off-grammar.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const STOCK = join(ROOT, 'node_modules/@deepseek-ai/dsh-client-ui-tool/lib/client.js')
const STOCK_PKG = join(ROOT, 'node_modules/@deepseek-ai/dsh-client-ui-tool/package.json')
const OUT = join(ROOT, 'plugins/artifact-viewer/lib/client.js')
const OUR_PREFIX = 'aXa_ins_'
const OPEN = '    // >>> insight-css'
const CLOSE = '    // <<< insight-css'

const SOURCES = [
  { tag: '@deepseek-ai/dsh-client-ui-tool/ToolRow.module.css', map: 'ToolRow_module_css_default', probe: 'ioSection' },
  { tag: '@deepseek-ai/dsh-client-ui-tool/ToolDetails.module.css', map: 'ToolDetails_module_css_default', probe: 'cardBody' },
]

const src = readFileSync(STOCK, 'utf8')
const dshVersion = JSON.parse(readFileSync(STOCK_PKG, 'utf8')).version

/** Lift one module: the `const css$N = "…"` literal right before its tagId, plus its class map. */
function lift({ tag, map, probe }) {
  const tagLine = src.indexOf('= ' + JSON.stringify(tag))
  if (tagLine < 0) throw new Error(tag + ': tagId not found — stock shape moved?')
  const cssStart = src.lastIndexOf('const css$', tagLine)
  if (cssStart < 0 || tagLine - cssStart > 20000) throw new Error(tag + ': css const before tagId not found')
  const line = src.slice(cssStart, src.indexOf('\n', cssStart))
  const q = line.indexOf('"')
  const css = JSON.parse(line.slice(q, line.lastIndexOf('"') + 1))
  const mapHead = 'var ' + map + ' = {'
  const mapAt = src.indexOf(mapHead)
  if (mapAt < 0) throw new Error(map + ' not found')
  const mapEnd = src.indexOf('}', mapAt)
  const classMap = Function('return {' + src.slice(mapAt + mapHead.length, mapEnd) + '}')()
  const prefix = classMap[probe].slice(0, classMap[probe].indexOf(probe))
  if (!prefix || !css.includes('.' + prefix + probe)) throw new Error(tag + ': hashed prefix not recoverable')
  return { css, classMap, prefix }
}

const parts = SOURCES.map(lift)
const I = {}
let css = ''
for (const p of parts) {
  for (const [k, v] of Object.entries(p.classMap)) {
    if (k in I) throw new Error('class name collision between ToolRow and ToolDetails: ' + k)
    I[k] = v.split(p.prefix).join(OUR_PREFIX)
  }
  css += p.css.split(p.prefix).join(OUR_PREFIX)
}
if (css.includes('o3BgMG_') || css.includes('xDAfVq_')) throw new Error('a stock prefix survived the rewrite')

const region = [
  OPEN + ' — GENERATED by scripts/gen-insight-css.mjs from @deepseek-ai/dsh-client-ui-tool',
  '    // ToolRow.module.css + ToolDetails.module.css (dsh ' + dshVersion + '), ' + parts.length + ' stock hashed prefixes rewritten → ' + OUR_PREFIX + ' (the raw prefixes are deliberately not named here — selftest asserts none leak).',
  '    // Do not hand-edit — `--check` is the selftest drift gate.',
  '    const INSIGHT_CSS = ' + JSON.stringify(css),
  '    const I = ' + JSON.stringify(I, null, 2).split('\n').map((l, i) => (i === 0 ? l : '    ' + l)).join('\n'),
  CLOSE,
].join('\n')

const cur = readFileSync(OUT, 'utf8')
const a = cur.indexOf(OPEN)
const b = cur.indexOf(CLOSE)
if (a < 0 || b < 0 || b < a) throw new Error('insight-css markers missing from ' + OUT)
const next = cur.slice(0, a) + region + cur.slice(b + CLOSE.length)

const args = new Set(process.argv.slice(2))
if (args.has('--write')) {
  writeFileSync(OUT, next)
  console.log('wrote insight-css region: ' + css.length + ' css chars, ' + Object.keys(I).length + ' classes (dsh ' + dshVersion + ')')
} else if (args.has('--check')) {
  if (next !== cur) { console.error('DRIFT: insight-css region differs from the stock bundle — run gen-insight-css.mjs --write'); process.exit(1) }
  console.log('--check OK: insight-css region matches dsh ' + dshVersion)
} else {
  console.log((next === cur ? 'in sync' : 'DRIFT') + ' — ' + css.length + ' css chars; --write to emit')
}
