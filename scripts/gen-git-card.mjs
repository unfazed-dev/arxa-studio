#!/usr/bin/env node
// Browser half of arxa-git-card — GENERATOR (docs/plans/git-card-stock-dock-rebuild.md A3).
//
// The Git card is the `conversation.input.dock` entry between the stock goal
// strip (order 10) and the stock queue strip (order 20; todo is 0). Its LOOK is the stock
// QueueDock's, byte-for-byte: this script lifts QueueDock.module.css and its
// class map out of @deepseek-ai/dsh-client-ui-conversation/lib/client.js,
// rewrites the identity (tagId + class prefix) so the two never collide, and
// wraps the hand-written card body (lib/git-card.snippet.txt) in the
// documented no-build `__ModuleLoader__` shape. Nothing is styled by hand —
// if the stock dock changes, regenerate and the card follows.
//
//   node scripts/gen-git-card.mjs           # print byte count + drift verdict
//   node scripts/gen-git-card.mjs --write   # write plugins/arxa-git-card/lib/client.js
//   node scripts/gen-git-card.mjs --check   # exit 1 when lib/client.js drifts
//
// Deviation from the plan text "drop editor/preview": `.editor` is KEPT — the
// commit-subject entry reuses the stock inline-edit grammar (input.editor,
// Enter saves, Escape cancels) instead of inventing a field; `.preview` is
// kept for the row text. Dropping nothing = nothing to get wrong.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import vm from 'node:vm'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const STOCK = join(ROOT, 'node_modules/@deepseek-ai/dsh-client-ui-conversation/lib/client.js')
const STOCK_PKG = join(ROOT, 'node_modules/@deepseek-ai/dsh-client-ui-conversation/package.json')
const SNIPPET = join(ROOT, 'plugins/arxa-git-card/lib/git-card.snippet.txt')
const OUT = join(ROOT, 'plugins/arxa-git-card/lib/client.js')

const STOCK_TAG = '@deepseek-ai/dsh-client-ui-conversation/QueueDock.module.css'
const STOCK_PREFIX = '_7yHdaG_'
const OUR_TAG = 'arxa-git-card/GitDock.module.css'
const OUR_PREFIX = 'aXa_gc_'
const NS = 'arxa-git-card'

const args = new Set(process.argv.slice(2))
const src = readFileSync(STOCK, 'utf8')
const dshVersion = JSON.parse(readFileSync(STOCK_PKG, 'utf8')).version

// ---- 1. lift the stock CSS literal (the const right before the tagId) -----
const tagAt = src.indexOf('const tagId$' )
const tagLine = src.indexOf('= ' + JSON.stringify(STOCK_TAG))
if (tagLine < 0) throw new Error('QueueDock tagId not found — stock shape moved?')
const cssStart = src.lastIndexOf('const css$', tagLine)
if (cssStart < 0 || cssStart < tagAt - 400000) throw new Error('css const before QueueDock tagId not found')
const cssLine = src.slice(cssStart, src.indexOf('\n', cssStart))
const lit = cssLine.slice(cssLine.indexOf('"'), cssLine.lastIndexOf('"') + 1)
let css = vm.runInNewContext('(' + lit + ')')
if (!css.includes('.' + STOCK_PREFIX + 'dock{')) throw new Error('lifted CSS is not QueueDock.module.css')

// ---- 2. lift the class map --------------------------------------------------
const mapHead = 'var QueueDock_module_css_default = {'
const mapAt = src.indexOf(mapHead)
if (mapAt < 0) throw new Error('QueueDock class map not found')
const mapEnd = src.indexOf('};', mapAt)
const mapBody = src.slice(mapAt + mapHead.length, mapEnd)
const classMap = vm.runInNewContext('({' + mapBody + '})')
const expectKeys = ['action', 'actions', 'chevron', 'count', 'dock', 'editor', 'header', 'lead', 'list', 'panel', 'preview', 'row']
for (const k of expectKeys) if (!(k in classMap)) throw new Error('stock class map lost key ' + k)

// ---- 3. identity rewrite ----------------------------------------------------
if (!css.includes(STOCK_PREFIX)) throw new Error('stock prefix missing from CSS')
css = css.split(STOCK_PREFIX).join(OUR_PREFIX)
const S = {}
for (const [k, v] of Object.entries(classMap)) S[k] = v.replace(STOCK_PREFIX, OUR_PREFIX)
// the card is not a queue: swap the data hook so stock selectors/tests never match it
if (css.includes('data-queue-dock')) css = css.split('data-queue-dock').join('data-git-dock')

// ---- 4. the card body ---------------------------------------------------------
if (!existsSync(SNIPPET)) throw new Error('missing ' + SNIPPET)
const snippet = readFileSync(SNIPPET, 'utf8').replace(/\s+$/, '')
if (!snippet.includes('function GitDock(')) throw new Error('snippet must define GitDock')

// ---- 5. compose -----------------------------------------------------------------
const T = (n) => '  '.repeat(n)
const out = [
  '// Browser half of arxa-git-card. GENERATED by scripts/gen-git-card.mjs from',
  '// @deepseek-ai/dsh-client-ui-conversation lib/client.js (dsh ' + dshVersion + ')',
  '// QueueDock.module.css + lib/git-card.snippet.txt. Do not hand-edit: regenerate',
  '// and let the selftest drift gate compare bytes. The stock QueueDock CSS is',
  '// carried whole under its own identity (' + OUR_TAG + ',',
  '// prefix ' + OUR_PREFIX + '); the component tree mirrors QueueDock (dock > panel >',
  '// header[lead,count,chevron] + list > row[preview|editor, actions > action]).',
  '',
  "window.__ModuleLoader__.load({",
  T(1) + "id: '" + NS + "',",
  T(1) + 'factory: (require) => {',
  T(2) + 'var module = { exports: {} }',
  T(2) + 'var exports = module.exports',
  T(2) + "Object.defineProperty(exports, Symbol.toStringTag, { value: 'Module' })",
  T(2) + "const React = require('react')",
  T(2) + 'const h = React.createElement',
  T(2) + "const P = require('@deepseek-ai/dsh-client-ui-primitives')",
  '',
  T(2) + "const NS = '" + NS + "'",
  T(2) + "const CARD_ROUTE = '/__arxa/git-card/action'",
  T(2) + "const CSS_TAG = '" + OUR_TAG + "'",
  T(2) + 'const CSS = ' + JSON.stringify(css),
  T(2) + 'const S = ' + JSON.stringify(S, null, 2).split('\n').join('\n' + T(2)),
  T(2) + 'function ensureCss() {',
  T(3) + "if (typeof document === 'undefined' || document.querySelector('style[data-plugin-css=' + JSON.stringify(CSS_TAG) + ']')) return",
  T(3) + "const tag = document.createElement('style')",
  T(3) + "tag.dataset.plugin = NS",
  T(3) + 'tag.dataset.pluginCss = CSS_TAG',
  T(3) + 'tag.textContent = CSS',
  T(3) + 'document.head.appendChild(tag)',
  T(2) + '}',
  '',
  T(2) + '// ---- card body (lib/git-card.snippet.txt) ----',
  snippet.split('\n').map((l) => (l === '' ? '' : T(2) + l)).join('\n'),
  '',
  T(2) + 'function apply(ctx) {',
  T(3) + 'ensureCss()',
  T(3) + "ctx.effect(() => ctx.locale.register(NS, { en, pl, fr }), 'arxa-git-card: dictionaries')",
  T(3) + "ctx.slots.inject('conversation.input.dock', () => ctx.slots.register({",
  T(4) + "name: 'conversation.input.dock',",
  T(4) + "id: 'git',",
  T(4) + 'order: 15,',
  T(4) + 'locale: NS,',
  T(4) + 'inject: (sessionId) => {',
  T(5) + 'const actx = ctx.sessions.scope(sessionId)',
  T(5) + 'let notify = (level, text) => { try { console[level === \'error\' ? \'error\' : \'log\']("[git-card] " + text) } catch {} }',
  T(5) + 'try {',
  T(6) + "const conversation = actx !== void 0 ? actx.get('conversation') : void 0",
  T(6) + 'if (conversation !== void 0) notify = (level, text) => { conversation.input.for(actx).notify(level, text) }',
  T(5) + '} catch {}',
  T(5) + 'return { sessionId, postAction, notify }',
  T(4) + '},',
  T(3) + '}, GitDock))',
  T(2) + '}',
  T(2) + "const inject = ['slots', 'sessions', 'locale']",
  T(2) + 'exports.apply = apply',
  T(2) + 'exports.inject = inject',
  T(2) + 'return module.exports',
  T(1) + '},',
  '})',
  '',
].join('\n')

// parse gate: the bundle must be a valid script before it is ever served
new vm.Script(out, { filename: 'arxa-git-card/lib/client.js' })

const prev = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null
const same = prev === out
if (args.has('--write')) {
  writeFileSync(OUT, out)
  console.log('written ' + Buffer.byteLength(out) + ' bytes (css ' + css.length + ') — parse-checked' + (same ? ' — unchanged' : ''))
} else if (args.has('--check')) {
  if (!same) { console.error('DRIFT: lib/client.js differs from the generator output — run gen-git-card.mjs --write'); process.exit(1) }
  console.log('git-card client: in sync (' + Buffer.byteLength(out) + ' bytes)')
} else {
  console.log((same ? 'in sync' : prev === null ? 'not yet written' : 'DRIFT') + ' — ' + Buffer.byteLength(out) + ' bytes; --write to emit')
}
